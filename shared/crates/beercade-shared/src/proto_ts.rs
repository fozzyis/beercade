    #[test]
    fn generated_ts_matches_checked_in_proto_exactly() {
        let expected = generate_typescript();
        assert!(!expected.contains("\r\n"), "generated TS must use LF only");
        let path = proto_ts_path();
        let on_disk = std::fs::read_to_string(&path).unwrap_or_else(|e| {
            panic!("failed to read {}: {e}", path.display());
        });
        assert_eq!(
            on_disk,
            expected,
            "shared/proto/telemetry.ts is out of sync with Rust models; run `cargo run -p beercade-shared --bin gen_ts_proto -- --write`"
        );
    }
