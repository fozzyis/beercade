//! Canonical TypeScript wire-protocol generator and drift-check tests.
//!
//! Keeps `shared/proto/telemetry.ts` strictly synchronized with the Rust wire
//! contracts in [`crate::models`] and theme constants in [`crate::theme`].

use crate::theme::{AVAILABLE_THEMES, DEFAULT_THEME};
use std::fmt::Write as _;

/// Generates the full contents of `shared/proto/telemetry.ts` using LF (`\n`) line endings.
pub fn generate_typescript() -> String {
    let mut out = String::with_capacity(4096);

    out.push_str("// GENERATED BY beercade-shared (`gen_ts_proto`) — DO NOT EDIT BY HAND.\n");
    out.push_str(
        "// Run `make gen-types` or `cargo run -p beercade-shared --bin gen_ts_proto -- --write`.\n\n",
    );

    // Theme constants from crate::theme
    out.push_str("export const AVAILABLE_THEMES = [\n");
    for theme in AVAILABLE_THEMES {
        let _ = writeln!(out, "\t\"{theme}\",");
    }
    out.push_str("] as const;\n\n");
    let _ = writeln!(
        out,
        "export type ThemeId = (typeof AVAILABLE_THEMES)[number];"
    );
    let _ = writeln!(out, "export const DEFAULT_THEME: ThemeId = \"{DEFAULT_THEME}\";\n");

    out.push_str(
        r#"export type StationMode =
	| { type: "Standalone" }
	| { type: "Managed"; payload: { session_id: string; time_remaining_sec: number } }
	| { type: "Locked"; payload: { reason: string } };

export interface InputJitterStats {
	poll_rate_hz: number;
	p50_us: number;
	p95_us: number;
	p99_us: number;
	max_us: number;
	dropped_events: number;
}

export interface NetplayStats {
	peer_id: string;
	rtt_ms: number;
	jitter_ms: number;
	packet_loss_pct: number;
	rollback_frames: number;
	is_host: boolean;
}

export interface CreditCounters {
	credits_available: number;
	credits_inserted_total: number;
	credits_dispensed_today: number;
	last_coin_epoch_ms?: number | null;
}

export interface NodeTelemetry {
	node_id: string;
	hardware: string;
	soc: string;
	cpu_temp_c?: number | null;
	gpu_temp_c?: number | null;
	npu_load_pct: number;
	active_core: string;
	active_rom: string;
	frame_time_ms: number;
	fps: number;
	input_jitter: InputJitterStats;
	netplay?: NetplayStats | null;
	credits: CreditCounters;
	mode: StationMode | Record<string, unknown> | null;
	timestamp_epoch_ms: number;
}

export interface VenueTelemetryReport {
	venue: string;
	address: string;
	status: string;
	nodes_online: number;
	nodes: NodeTelemetry[];
	generated_at_epoch_ms: number;
}

export interface GameRef {
	game_id: string;
	title: string;
	system: string;
	core: string;
	file_name: string;
	size_bytes: number;
	sha256: string;
	artwork_url?: string | null;
}

export type CabinetCommand =
	| { type: "reboot"; delay_secs: number }
	| { type: "launch_game"; core: string; rom: string; netplay: boolean }
	| { type: "add_credits"; credits: number }
	| { type: "ping"; seq: number }
	| {
			type: "start_session";
			session_id: string;
			duration_secs: number;
			session_code?: string;
			topup_grace_secs?: number;
			games?: GameRef[];
	  }
	| {
			type: "update_session";
			session_id: string;
			games?: GameRef[] | null;
			add_secs?: number;
	  }
	| {
			type: "end_session";
			session_id?: string | null;
			reason?: string | null;
	  }
	| { type: "start_attract"; games: GameRef[]; secs_per_game: number };

export type CabinetEvent =
	| {
			type: "session_staged";
			session_id: string;
			ready_game_ids: string[];
			failed_game_ids: string[];
	  }
	| { type: "game_started"; session_id: string; game_id: string }
	| { type: "game_exited"; session_id: string; game_id: string; crashed: boolean }
	| { type: "session_expired"; session_id: string }
	| { type: "session_ended"; session_id: string; files_wiped: boolean }
	| { type: "change_requested"; session_id: string }
	| { type: "attract_needed" };

export type CommandStatus = "queued" | "dispatched" | "acknowledged" | "failed";

export interface CommandRecord {
	id: string;
	node_id: string;
	command: CabinetCommand;
	status: CommandStatus;
	issued_at_epoch_ms: number;
	dispatched_at_epoch_ms?: number | null;
	completed_at_epoch_ms?: number | null;
	result?: unknown;
}

export interface CommandAck {
	command_id: string;
	success: boolean;
	detail?: unknown;
}

export interface ErrorEvent {
	node_id: string;
	level: string;
	source: string;
	message: string;
	detail?: unknown;
	occurred_at_epoch_ms: number;
}

export interface TokenTransaction {
	node_id: string;
	kind: string;
	credits: number;
	balance_after: number;
	command_id?: string | null;
	created_at_epoch_ms: number;
}

export interface HighScoreEntry {
	node_id: string;
	active_core: string;
	active_rom: string;
	game_name: string;
	score: number;
	initials: string;
	achieved_at_epoch_ms: number;
}

export interface EdgeBatchEnvelope {
	batch_id: string;
	venue: string;
	generated_at_epoch_ms: number;
	nodes: NodeTelemetry[];
	errors: ErrorEvent[];
	transactions: TokenTransaction[];
	scores: HighScoreEntry[];
}

export type WsServerMessage =
	| { kind: "command"; record: CommandRecord }
	| { kind: "theme_changed"; theme: string }
	| {
			kind: "payload_available";
			filename: string;
			sha256?: string | null;
			size_bytes?: number | null;
	  };
"#,
    );

    out
}

/// Returns the canonical path to `shared/proto/telemetry.ts` in this repository.
pub fn proto_ts_path() -> std::path::PathBuf {
    std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../proto/telemetry.ts")
}

